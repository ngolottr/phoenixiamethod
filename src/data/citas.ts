/* ============================================================================
   LAS FRASES DEL MÉTODO
   ----------------------------------------------------------------------------
   Una cita de un libro famoso por día, con su autor, su foto y el libro donde
   se escribió. Existe para dar credibilidad: alguien que llega desconfiando de
   una web de "IA y automatización" se encuentra con frases de gente que escribió
   los libros que ya conoce, y eso ubica el criterio de Phoenix en una tradición
   en vez de en un eslogan.

   EN UN SITIO QUE VIVE DE LA CREDIBILIDAD, UNA CITA FALSA ES PEOR QUE NINGUNA.
   Internet está lleno de frases mal atribuidas, y una sola mala en la sección
   que existe para dar confianza la desarma entera. Por eso NINGUNA de estas está
   aquí porque "suena a Drucker": cada una se buscó, palabra por palabra, dentro
   del texto de un libro escrito por esa misma persona.

   Cómo se verificó, según de dónde viene la frase:
     · Libros modernos: en el texto completo del libro (Open Library / Internet
       Archive), exigiendo que el principio, el medio y el final de la frase
       aparezcan en el mismo libro y en la misma página.
     · Clásicos de dominio público: en el libro entero (Project Gutenberg y
       Wikisource), con la traducción inglesa que se nombra en cada una.
     · Francés: en Wikiquote francés, con capítulo y edición.
   Se descartaron las frases que en el libro resultaron ser de otro (por ejemplo,
   una de Frankl que es de Nietzsche, o una de Kahneman que es de Herbert Simon)
   y las que el libro dice distinto de como circulan (Catmull escribió "equipo
   brillante", no "gran equipo").

   Además de la lista, hay que cuidar tres cosas:

   1. SE AGREGA SIEMPRE AL FINAL. La frase de cada día sale de una cuenta sobre
      esta lista (ver lib/citaDelDia.ts), así que insertar una en medio corre todas
      las siguientes y se repetiría una que ya salió.

   2. LA LISTA SE ACABA. Con 125 frases, la primera vuelta dura 125 días desde el
      lanzamiento. Después el sitio empieza a repetirlas (y deja de decir que no
      se repiten). `npm run citas` avisa cuántos días quedan, y avisa fuerte cuando
      son menos de 30.

   3. LAS FOTOS SON DE WIKIMEDIA COMMONS con licencia libre, y esa licencia exige
      nombrar a quien la hizo: por eso cada autor lleva su crédito y se muestra en
      pantalla. Nunca se agrega una foto sin licencia clara. Los archivos viven
      en public/images/autores/.

   Las traducciones al castellano son propias (el original va siempre a la vista,
   debajo). Cada cita es corta a propósito: una frase, con su autor y su libro.
   ========================================================================== */

export type Tema = 'negocios' | 'autoayuda' | 'ia'

export type Foto = {
  /** Ruta relativa a la raíz del sitio, en public/. */
  archivo: string
  /** Quién hizo la foto. Vacío cuando no se conoce (la licencia es de dominio público). */
  credito: string
  licencia: string
  /** La página del archivo en Wikimedia Commons, donde está la licencia completa. */
  enlace: string
  /** "retrato" cuando es una pintura, un grabado, un busto o una ilustración. */
  tipo: 'foto' | 'retrato'
  /** object-position, para los casos en que el rostro no queda en el centro. */
  posicion?: string
}

export type Autor = { nombre: string; foto: Foto }

export type Cita = {
  id: string
  /** La frase en castellano (traducción propia). */
  es: string
  /** La frase tal como se publicó, en su idioma original. */
  original: string
  idioma: 'en' | 'fr' | 'es'
  /** Palabra o tramo de `es` que se destaca con el color de la marca. */
  resaltar?: string
  autor: string
  /** Título original del libro. */
  libro: string
  /** Título con que se conoce en castellano, solo cuando se conoce con seguridad. */
  libroEs?: string
  /** Año de publicación; en los clásicos, el aproximado. */
  anio: number | string
  /** El pasaje: capítulo, libro o carta. */
  donde?: string
  /** Quién tradujo el original al inglés que se cita, en los clásicos. */
  traductor?: string
  nota?: string
  tema: Tema
}

